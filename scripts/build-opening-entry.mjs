import fs from 'node:fs/promises';

// Keep one iris implementation for its module tests and the early classic entry.
// No runtime imports, dynamic code execution or additional network hop is needed.
export async function buildOpeningEntry(){
 const source=new URL('../src/opening-sequence.js',import.meta.url);
 const opening=await fs.readFile(source,'utf8');
 if(/^\s*import\b/m.test(opening))throw Error('The opening entry must remain self-contained');
 const runtime=opening.replace(/^export (?=function\b)/gm,'');
 if(/^\s*export\b/m.test(runtime))throw Error('Unsupported opening entry export');
 const guard=await fs.readFile(new URL('../src/opening-startup.js',import.meta.url),'utf8');
 const entry=await fs.readFile(new URL('./opening-entry-runtime.js',import.meta.url),'utf8');
 await fs.writeFile(new URL('../src/opening-entry.js',import.meta.url),`// Generated by scripts/build-opening-entry.mjs. Edit its source files.\n${guard}\n(() => {\n${runtime}\n${entry}\n})();\n`);
}
